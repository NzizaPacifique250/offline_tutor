#!/usr/bin/env bash
# Record the tablet's hardware profile.
#
# Every later decision, which model, which quantization, how many threads and how
# large a context window, depends on these numbers. Run this first and commit the
# output, because it becomes the "target hardware" section of the dissertation.
#
# Usage: bench/scripts/00_device_profile.sh

. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_device

OUT="$RESULTS_DIR/device_profile.md"
JSON="$RESULTS_DIR/device_profile.json"
mkdir -p "$RESULTS_DIR"

# getprop returns an empty string for unknown keys, which is what we want.
gp() { adb shell getprop "$1" 2>/dev/null | tr -d '\r'; }

log "Reading device properties"

MODEL="$(gp ro.product.model)"
BRAND="$(gp ro.product.brand)"
DEVICE="$(gp ro.product.device)"
BOARD="$(gp ro.product.board)"
ANDROID_REL="$(gp ro.build.version.release)"
SDK="$(gp ro.build.version.sdk)"
ABILIST="$(gp ro.product.cpu.abilist)"
FINGERPRINT="$(gp ro.build.fingerprint)"

# Hardware detail has to come from procfs; getprop does not expose core counts.
CPU_HW="$(adb shell 'cat /proc/cpuinfo | grep -m1 -i "^Hardware" || true' 2>/dev/null | tr -d '\r')"
CORES="$(adb shell 'grep -c "^processor" /proc/cpuinfo' 2>/dev/null | tr -d '\r')"
CPU_FEATURES="$(adb shell 'grep -m1 "^Features" /proc/cpuinfo || true' 2>/dev/null | tr -d '\r')"

# MemTotal is in kB.
MEM_KB="$(adb shell 'grep MemTotal /proc/meminfo' 2>/dev/null | tr -d '\r' | awk '{print $2}')"
MEM_AVAIL_KB="$(adb shell 'grep MemAvailable /proc/meminfo' 2>/dev/null | tr -d '\r' | awk '{print $2}')"
MEM_GB="$(awk -v k="${MEM_KB:-0}" 'BEGIN{printf "%.2f", k/1048576}')"
MEM_AVAIL_GB="$(awk -v k="${MEM_AVAIL_KB:-0}" 'BEGIN{printf "%.2f", k/1048576}')"

# Maximum clock per core, in kHz, deduplicated.
MAX_FREQ="$(adb shell 'cat /sys/devices/system/cpu/cpu*/cpufreq/cpuinfo_max_freq 2>/dev/null' \
  | tr -d '\r' | sort -un | awk '{printf "%.2f GHz  ", $1/1000000}')"

# Free space on the partition that will hold the model file.
STORAGE="$(adb shell 'df -h /data 2>/dev/null | tail -1' | tr -d '\r')"

GPU_RENDERER="$(gp ro.hardware.egl)"
SOC_MODEL="$(gp ro.soc.model)"
SOC_MFR="$(gp ro.soc.manufacturer)"

# Big-core / little-core split, which determines the best thread count.
CORE_FREQS="$(adb shell 'for c in /sys/devices/system/cpu/cpu[0-9]*; do printf "%s:%s\n" "$(basename $c)" "$(cat $c/cpufreq/cpuinfo_max_freq 2>/dev/null || echo unknown)"; done' | tr -d '\r')"

# --- ARM extensions that matter for quantized inference ---
# dotprod (sdot/udot) accelerates Q4_0 and Q8_0 by a large factor.
# fphp/asimdhp are half-precision paths. i8mm is int8 matrix multiply.
have_feature() { case "$CPU_FEATURES" in *"$1"*) echo yes ;; *) echo no ;; esac; }
F_DOTPROD="$(have_feature asimddp)"
F_FP16="$(have_feature asimdhp)"
F_I8MM="$(have_feature i8mm)"
F_SVE="$(have_feature sve)"

{
  echo "# Target Device Profile"
  echo
  echo "Generated by \`bench/scripts/00_device_profile.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
  echo
  echo "## Identity"
  echo
  echo "| Property | Value |"
  echo "|---|---|"
  echo "| Model | ${MODEL:-unknown} |"
  echo "| Brand | ${BRAND:-unknown} |"
  echo "| Device | ${DEVICE:-unknown} |"
  echo "| Board | ${BOARD:-unknown} |"
  echo "| System on chip | ${SOC_MFR:-unknown} ${SOC_MODEL:-} |"
  echo "| Android release | ${ANDROID_REL:-unknown} (API ${SDK:-unknown}) |"
  echo "| Supported ABIs | ${ABILIST:-unknown} |"
  echo "| Build fingerprint | \`${FINGERPRINT:-unknown}\` |"
  echo
  echo "## Compute"
  echo
  echo "| Property | Value |"
  echo "|---|---|"
  echo "| CPU cores | ${CORES:-unknown} |"
  echo "| Maximum clocks | ${MAX_FREQ:-unknown} |"
  echo "| Hardware string | ${CPU_HW:-not reported} |"
  echo "| GPU driver | ${GPU_RENDERER:-unknown} |"
  echo
  echo "Per-core maximum frequency in kHz:"
  echo
  echo '```'
  echo "$CORE_FREQS"
  echo '```'
  echo
  echo "## ARM extensions relevant to quantized inference"
  echo
  echo "| Extension | Present | Why it matters |"
  echo "|---|---|---|"
  echo "| asimddp (dot product) | $F_DOTPROD | Large speedup on Q4_0 and Q8_0 kernels |"
  echo "| asimdhp (fp16 arithmetic) | $F_FP16 | Faster half-precision paths |"
  echo "| i8mm (int8 matrix multiply) | $F_I8MM | Faster prompt processing |"
  echo "| sve | $F_SVE | Rare on tablet-class cores |"
  echo
  echo "CPU feature line as reported by the kernel:"
  echo
  echo '```'
  echo "${CPU_FEATURES:-not reported}"
  echo '```'
  echo
  echo "## Memory and storage"
  echo
  echo "| Property | Value |"
  echo "|---|---|"
  echo "| Total RAM | ${MEM_GB} GB |"
  echo "| Available RAM at scan time | ${MEM_AVAIL_GB} GB |"
  echo "| /data partition | \`${STORAGE:-unknown}\` |"
  echo
  echo "## Reading these numbers"
  echo
  echo "Total RAM sets the hard ceiling on model size. Android's low-memory killer"
  echo "will terminate a foreground application well before it reaches the total, so"
  echo "the practical budget for model weights plus the key-value cache is roughly"
  echo "half of available RAM. Compare that budget against the model file sizes in"
  echo "\`results/bench_summary.md\` before choosing what to ship."
} > "$OUT"

# Machine-readable copy, so later scripts and the report generator can read it
# without re-parsing the Markdown.
cat > "$JSON" <<EOF
{
  "generated_utc": "$(date -u '+%Y-%m-%dT%H:%M:%SZ')",
  "model": "${MODEL}",
  "brand": "${BRAND}",
  "device": "${DEVICE}",
  "board": "${BOARD}",
  "soc_manufacturer": "${SOC_MFR}",
  "soc_model": "${SOC_MODEL}",
  "android_release": "${ANDROID_REL}",
  "sdk": "${SDK}",
  "abilist": "${ABILIST}",
  "cpu_cores": ${CORES:-0},
  "mem_total_gb": ${MEM_GB},
  "mem_available_gb": ${MEM_AVAIL_GB},
  "features": {
    "asimddp": "${F_DOTPROD}",
    "asimdhp": "${F_FP16}",
    "i8mm": "${F_I8MM}",
    "sve": "${F_SVE}"
  }
}
EOF

log "Wrote $OUT"
log "Wrote $JSON"
echo
cat "$OUT"
