#!/usr/bin/env bash
# Toolchain for building and installing the app.
# Source this before any gradle, adb or react-native command:
#   . app/scripts/env.sh
#
# Mirrors bench/scripts/lib.sh: everything lives under $HOME/Android and needs
# no sudo. Versions are pinned to what React Native 0.87.1 requires.

export ANDROID_TOOLS="${ANDROID_TOOLS:-$HOME/Android}"
export JAVA_HOME="${JAVA_HOME:-$ANDROID_TOOLS/jdk-17.0.20.1+1}"
export ANDROID_HOME="${ANDROID_HOME:-$ANDROID_TOOLS/Sdk}"
export ANDROID_SDK_ROOT="$ANDROID_HOME"
export PATH="$JAVA_HOME/bin:$ANDROID_HOME/platform-tools:$ANDROID_HOME/cmdline-tools/latest/bin:$PATH"

# Application identity, shared by the staging and diagnostic scripts.
export APP_ID="rw.offlinetutor"

# Where the benchmark kit staged the candidate models on the tablet.
export DEVICE_MODELS_DIR="/data/local/tmp/tutor-bench/models"

# The provisional model from docs/FEASIBILITY_FINDINGS.md.
export MODEL_FILE="qwen25-math-1.5b-Qwen2.5-Math-1.5B-Instruct-Q4_K_M.gguf"

app_log()  { printf '\033[1;34m[app]\033[0m %s\n' "$*"; }
app_die()  { printf '\033[1;31m[fail]\033[0m %s\n' "$*" >&2; exit 1; }

# A CMake directory whose ninja caps parallel compile jobs. android/local.properties
# points cmake.dir here. The Android Gradle plugin runs ninja with no -j, which on
# this 12-core, 8 GB host meant fourteen concurrent compilers and an OOM kill of
# the whole editor session on the first build.
export CMAKE_LIMITED="$ANDROID_TOOLS/cmake-limited"
export NINJA_JOBS="${NINJA_JOBS:-3}"

app_ensure_cmake_limited() {
  local sdk_cmake="$ANDROID_HOME/cmake/3.22.1"
  [ -x "$sdk_cmake/bin/ninja" ] || app_die "SDK CMake 3.22.1 missing (the Android Gradle plugin installs it on first build)"
  mkdir -p "$CMAKE_LIMITED/bin"
  for tool in cmake cpack ctest; do
    ln -sfn "$sdk_cmake/bin/$tool" "$CMAKE_LIMITED/bin/$tool"
  done
  ln -sfn "$sdk_cmake/share" "$CMAKE_LIMITED/share"
  cat > "$CMAKE_LIMITED/bin/ninja" <<EOF
#!/usr/bin/env bash
# Generated by app/scripts/env.sh. Caps ninja parallelism; see NINJA_JOBS.
exec "$sdk_cmake/bin/ninja" -j "\${NINJA_JOBS:-3}" "\$@"
EOF
  chmod +x "$CMAKE_LIMITED/bin/ninja"
}

# Verify the toolchain is really there before a long build starts.
app_check_toolchain() {
  [ -x "$JAVA_HOME/bin/java" ] || app_die "JDK not found at $JAVA_HOME"
  [ -d "$ANDROID_HOME/platforms/android-37.0" ] || app_die "platforms;android-37.0 missing. Run: sdkmanager 'platforms;android-37.0'"
  [ -d "$ANDROID_HOME/build-tools/37.0.0" ] || app_die "build-tools;37.0.0 missing. Run: sdkmanager 'build-tools;37.0.0'"
  [ -d "$ANDROID_HOME/ndk/27.1.12297006" ] || app_die "ndk;27.1.12297006 missing"
  command -v adb >/dev/null || app_die "adb not on PATH"
  [ -x "$CMAKE_LIMITED/bin/ninja" ] || app_ensure_cmake_limited
}
