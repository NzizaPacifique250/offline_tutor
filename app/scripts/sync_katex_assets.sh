#!/usr/bin/env bash
# Copy KaTeX's runtime into the Android assets directory.
#
# LessonView renders mathematics in a WebView whose base URL is
# file:///android_asset/katex/, so the JavaScript, stylesheet and fonts must be
# packaged inside the APK. They are regenerated from node_modules and are not
# committed. Run before every build; run_debug.sh does so.

set -euo pipefail
APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$APP_DIR/node_modules/katex/dist"
DST="$APP_DIR/android/app/src/main/assets/katex"

[ -f "$SRC/katex.min.js" ] || { echo "katex not installed: npm install" >&2; exit 1; }
mkdir -p "$DST/fonts"
cp "$SRC/katex.min.js" "$SRC/katex.min.css" "$DST/"
# KaTeX's CSS references woff2 first; the other formats are fallbacks the
# Android WebView never needs.
cp "$SRC"/fonts/*.woff2 "$DST/fonts/"
printf '%s\n' "$(node -p "require('$APP_DIR/node_modules/katex/package.json').version")" > "$DST/VERSION"

# The auto-render extension finds \( \) and \[ \] delimiters in generated
# text. It is inlined into the page as a string so that no new APK asset is
# needed; the generated module is gitignored like the curriculum packages.
GEN="$APP_DIR/src/katex/autoRender.ts"
{
  echo "// GENERATED by scripts/sync_katex_assets.sh from katex/dist/contrib/auto-render.min.js."
  echo "// Do not edit; run the script."
  echo "export const AUTO_RENDER_JS = $(node -e "process.stdout.write(JSON.stringify(require('fs').readFileSync('$SRC/contrib/auto-render.min.js', 'utf8')))");"
} > "$GEN"
echo "katex $(cat "$DST/VERSION") -> $DST ($(du -sh "$DST" | cut -f1)); auto-render -> src/katex/autoRender.ts"
