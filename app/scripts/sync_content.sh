#!/usr/bin/env bash
# Validate every curriculum package and copy it into the application bundle.
#
# Packages live in curriculum/<curriculum>/packages/<unit>/ and are the single
# source of truth. Metro can only bundle files under the app directory, so this
# copies the JSON into src/content/packages/ (gitignored, regenerated on every
# build) and writes an index.ts that imports each package with types. A package
# that fails tools/validate_package.py stops the build.
#
# Usage: app/scripts/sync_content.sh

set -euo pipefail
APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(dirname "$APP_DIR")"
PY="$ROOT/.venv/bin/python"
SRC="$ROOT/curriculum/rw_s6_mathematics/packages"
DST="$APP_DIR/src/content/packages"

[ -x "$PY" ] || { echo "project virtualenv missing: $PY" >&2; exit 1; }
[ -d "$SRC" ] || { echo "no packages under $SRC" >&2; exit 1; }

rm -rf "$DST"
mkdir -p "$DST"
index="$DST/index.ts"
{
  echo "// GENERATED by scripts/sync_content.sh from curriculum/rw_s6_mathematics/packages/."
  echo "// Do not edit; edit the package JSON and run the script."
  echo "import type { ContentPackage } from '../types';"
} > "$index"

entries=()
for pkg in "$SRC"/*/; do
  name="$(basename "$pkg")"
  "$PY" "$ROOT/tools/validate_package.py" "$pkg" --quiet
  mkdir -p "$DST/$name"
  cp "$pkg"/package.json "$pkg"/lessons.json "$pkg"/examples.json "$pkg"/exercises.json "$DST/$name/"
  {
    echo "import ${name}_manifest from './$name/package.json';"
    echo "import ${name}_lessons from './$name/lessons.json';"
    echo "import ${name}_examples from './$name/examples.json';"
    echo "import ${name}_exercises from './$name/exercises.json';"
  } >> "$index"
  entries+=("$name")
done

{
  echo ""
  echo "export const PACKAGES: ContentPackage[] = ["
  for name in "${entries[@]}"; do
    echo "  {"
    echo "    manifest: ${name}_manifest as unknown as ContentPackage['manifest'],"
    echo "    lessons: ${name}_lessons as unknown as ContentPackage['lessons'],"
    echo "    examples: ${name}_examples as unknown as ContentPackage['examples'],"
    echo "    exercises: ${name}_exercises as unknown as ContentPackage['exercises'],"
    echo "  },"
  done
  echo "];"
} >> "$index"

echo "content: ${#entries[@]} package(s) validated and bundled -> src/content/packages/ (${entries[*]})"
