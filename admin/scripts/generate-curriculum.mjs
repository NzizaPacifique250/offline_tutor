// Regenerates lib/curriculum.ts from the curriculum packages.
// Run from admin/: npm run curriculum
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..", "..", "curriculum", "rw_s6_mathematics", "packages");
const units = ["u1", "u4", "u5", "u9"];
const lessons = [];
const exercises = {};

for (const unit of units) {
  const read = (name) => JSON.parse(readFileSync(join(root, unit, name), "utf8"));
  const unitTitle = read("package.json").unit_title;
  const unitExercises = read("exercises.json");
  for (const lesson of read("lessons.json")) {
    const ids = unitExercises.filter((e) => e.lesson === lesson.id).map((e) => e.id);
    lessons.push({ id: lesson.id, title: lesson.title, unit: unitTitle, exerciseIds: ids });
  }
  for (const e of unitExercises) exercises[e.id] = e.source_label;
}

const out = `// Generated by scripts/generate-curriculum.mjs. Do not edit by hand.
export type Lesson = { id: string; title: string; unit: string; exerciseIds: string[] };

export const LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 2)};

export const EXERCISE_LABELS: Record<string, string> = ${JSON.stringify(exercises, null, 2)};

export function lessonTitle(id: string | null): string {
  if (!id) return "No lesson";
  return LESSONS.find((l) => l.id === id)?.title ?? id;
}

export function exerciseLabel(id: string | null): string {
  if (!id) return "";
  return EXERCISE_LABELS[id] ?? id;
}
`;
writeFileSync(join(import.meta.dirname, "..", "lib", "curriculum.ts"), out);
console.log(`${lessons.length} lessons, ${Object.keys(exercises).length} exercises`);
